-- USEF results export: section codes, competition ID, and the entry fields the
-- USEF universal results file needs.
--
-- Section codes come from USEF's "2026 section codes" list (606 codes). A class
-- carries one, chosen when the class is set up, and it flows through to the
-- results export. Everything here is additive: new nullable columns and one new
-- reference table, so no existing row or behavior changes.

create table if not exists public.usef_section_codes (
  code text primary key check (code ~ '^[0-9]+$'),
  division_name text not null,
  section_name text not null,
  sort_order integer not null
);

comment on table public.usef_section_codes is
  'USEF section codes (2026 list). Reference data; read by any signed-in user, written only by migrations.';

alter table public.usef_section_codes enable row level security;

create policy usef_section_codes_read on public.usef_section_codes
  for select to authenticated using (true);

